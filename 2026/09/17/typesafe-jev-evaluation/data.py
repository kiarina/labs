def ticket_questions(lang: str) -> dict:
    text = QUESTION_TEXT[lang]
    instructions, descriptions = text["department"]
    score_instructions, levels = text["frustration"]
    return {
        "department": {"type": "choice", "instructions": instructions,
                       "criteria": dict(zip(DEPARTMENTS, descriptions))},
        "urgent": {"type": "noul", "instructions": text["urgent"]},
        "frustration": {"type": "score", "instructions": score_instructions, "criteria": levels},
    }


